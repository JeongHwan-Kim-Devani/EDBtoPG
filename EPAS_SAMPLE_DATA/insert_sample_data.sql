-- EPAS 전용(Oracle 호환) 샘플 데이터/객체 스크립트
-- PostgreSQL에서는 동작하지 않는 문법/객체를 의도적으로 포함합니다.

CREATE SCHEMA IF NOT EXISTS demo;

CREATE TABLE IF NOT EXISTS demo.customers (
  customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(200) UNIQUE NOT NULL,
  created_at DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE IF NOT EXISTS demo.orders (
  order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES demo.customers(customer_id),
  product_name VARCHAR2(100) NOT NULL,
  quantity NUMBER(10) NOT NULL,
  unit_price NUMBER(12,2) NOT NULL,
  ordered_at DATE DEFAULT SYSDATE NOT NULL
);


CREATE UNIQUE INDEX IF NOT EXISTS ux_demo_orders_nk
  ON demo.orders (customer_id, product_name, quantity, unit_price);

-- Oracle 타입 호환 (CLOB/BLOB)
CREATE TABLE IF NOT EXISTS demo.customer_docs (
  doc_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES demo.customers(customer_id),
  doc_name VARCHAR2(200) NOT NULL UNIQUE,
  doc_text CLOB,
  doc_bin BLOB,
  created_at DATE DEFAULT SYSDATE
);

-- 다양한 타입 샘플(최소 10개 타입)
CREATE TABLE IF NOT EXISTS demo.type_samples (
  sample_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  v_varchar2 VARCHAR2(100) UNIQUE,
  v_char CHAR(10),
  v_number NUMBER(18,4),
  v_integer INTEGER,
  v_date DATE,
  v_timestamp TIMESTAMP,
  v_clob CLOB,
  v_blob BLOB,
  v_nvarchar2 NVARCHAR2(100),
  v_interval INTERVAL DAY TO SECOND,
  v_flag CHAR(1)
);

-- 데이터 분산 저장용 추가 테이블들
CREATE TABLE IF NOT EXISTS demo.large_text_chunks (
  chunk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chunk_name VARCHAR2(100) UNIQUE,
  chunk_text CLOB,
  created_at DATE DEFAULT SYSDATE
);

CREATE TABLE IF NOT EXISTS demo.large_binary_chunks (
  chunk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chunk_name VARCHAR2(100) UNIQUE,
  chunk_bin BLOB,
  created_at DATE DEFAULT SYSDATE
);


