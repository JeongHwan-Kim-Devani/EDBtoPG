-- PACKAGE + AUTHID 추가 예시(카운트 보강)
CREATE OR REPLACE PACKAGE demo.pkg_text_api AUTHID CURRENT_USER IS
  FUNCTION fn_make_clob(p_seed IN VARCHAR2) RETURN CLOB;
END pkg_text_api;

CREATE OR REPLACE PACKAGE BODY demo.pkg_text_api IS
  FUNCTION fn_make_clob(p_seed IN VARCHAR2) RETURN CLOB IS
    v_txt CLOB;
  BEGIN
    v_txt := TO_CLOB(p_seed || ':' || SYS_CONTEXT('USERENV', 'SESSION_USER'));
    RETURN NVL(v_txt, TO_CLOB('N/A'));
  END fn_make_clob;
END pkg_text_api;



