-- 1MB 페이로드 생성 함수(32자 md5 * 32768 = 1,048,576 bytes)
CREATE OR REPLACE FUNCTION demo.fn_payload_1mb(p_seed TEXT)
RETURNS TEXT
LANGUAGE SQL
IMMUTABLE
AS $$
  SELECT STRING_AGG(MD5(p_seed || ':' || gs::TEXT), '')
  FROM generate_series(1, 32768) gs;
$$;

