-- Policy(VPD) function + policy 등록
CREATE OR REPLACE FUNCTION demo.fn_customer_policy(
  p_schema_name VARCHAR2,
  p_object_name VARCHAR2
)
RETURNS VARCHAR2
LANGUAGE edbspl
AS $$
BEGIN
  RETURN 'email = SYS_CONTEXT(''USERENV'', ''SESSION_USER'')';
END;
$$;

DO $$
BEGIN
  BEGIN
    PERFORM DBMS_RLS.DROP_POLICY('DEMO', 'CUSTOMERS', 'CUSTOMER_EMAIL_POLICY');
  EXCEPTION
    WHEN OTHERS THEN
      NULL;
  END;

  PERFORM DBMS_RLS.ADD_POLICY(
    object_schema   => 'DEMO',
    object_name     => 'CUSTOMERS',
    policy_name     => 'CUSTOMER_EMAIL_POLICY',
    function_schema => 'DEMO',
    policy_function => 'FN_CUSTOMER_POLICY',
    statement_types => 'SELECT'
  );
END
$$;
