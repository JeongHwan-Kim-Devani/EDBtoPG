-- Procedure (EPAS 전용 language: edbspl)
CREATE OR REPLACE PROCEDURE demo.pr_add_order(
  p_email        VARCHAR2,
  p_product_name VARCHAR2,
  p_quantity     NUMBER,
  p_unit_price   NUMBER
)
LANGUAGE edbspl
AS $$
DECLARE
  v_customer_id BIGINT;
BEGIN
  SELECT customer_id
    INTO v_customer_id
    FROM demo.customers
   WHERE email = p_email;

  INSERT INTO demo.orders (customer_id, product_name, quantity, unit_price, ordered_at)
  VALUES (v_customer_id, p_product_name, p_quantity, p_unit_price, SYSDATE);
END;
$$;

-- Function (EPAS 전용 language: edbspl)
CREATE OR REPLACE FUNCTION demo.fn_total_amount(p_email VARCHAR2)
RETURNS NUMBER
LANGUAGE edbspl
AS $$
DECLARE
  v_total NUMBER;
BEGIN
  SELECT NVL(SUM(o.quantity * o.unit_price), 0)
    INTO v_total
    FROM demo.orders o
    JOIN demo.customers c ON c.customer_id = o.customer_id
   WHERE c.email = p_email;

  RETURN v_total;
END;
$$;

-- 약 500MB 샘플 데이터 적재(대용량 CLOB)
-- 재실행 시 누적량이 500MB(1MB x 500건) 수준이 되도록 부족분만 추가합니다.
DO $$
DECLARE
  v_target_mb INTEGER := 500;
  v_existing_rows INTEGER;
  v_missing_rows INTEGER;
BEGIN
  SELECT COUNT(*)
    INTO v_existing_rows
    FROM demo.customer_docs
   WHERE doc_name LIKE 'bulk_doc_%';

  v_missing_rows := GREATEST(v_target_mb - v_existing_rows, 0);

  IF v_missing_rows > 0 THEN
    INSERT INTO demo.customer_docs (customer_id, doc_name, doc_text, doc_bin, created_at)
    SELECT c.customer_id,
           'bulk_doc_' || TO_CHAR(gs),
           CAST(REPEAT('X', 1024 * 1024) AS CLOB),
           NULL,
           SYSDATE
      FROM generate_series(v_existing_rows + 1, v_existing_rows + v_missing_rows) gs
      CROSS JOIN (
        SELECT customer_id
          FROM demo.customers
         WHERE email = 'minjun@example.com'
         FETCH FIRST 1 ROW ONLY
      ) c;
  END IF;
END
$$;

